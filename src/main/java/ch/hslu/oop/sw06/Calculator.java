package ch.hslu.oop.sw06;

public class Calculator {
  private float a;
  private float b;


  public float getAdd(float a, float b){
    return a + b;
  }

  public float getSub(float a, float b){
    return a - b;
  }

  public float getMulti(float a, float b){
    return a * b;
  }

  public float getDiv(float a, float b){
    return a / b;
  }


}
